1. **製造上の欠陥**：設計どおりに作られなかった（異物混入、部品の取り付けミス等）
2. **設計上の欠陥**：設計自体に問題があった（構造的に安全性を欠く）
3. **指示・警告上の欠陥**：危険性の表示・説明が不十分だった（「子どもの手の届かない場所に保管」の記載漏れ等）

**開発危険の抗弁：** 製品を引き渡した時点では科学・技術の知見では欠陥を認識できなかったと証明できれば、製造業者は免責されます。

